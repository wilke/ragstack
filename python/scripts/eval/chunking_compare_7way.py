def describe_overlap(cfg: ChunkConfig) -> str:
    """``"64 tok (12.5%)"`` — the resolved absolute AND the fraction it came from.

    A report that shows only the absolute makes a size ladder unreadable (64 is
    25% at 256 and 3.1% at 2048); one that shows only the fraction hides what was
    actually handed to the chunker. Both, always.
    """
    unit = "char" if cfg.kind == "fixed_char" else "tok"
    if cfg.overlap_frac is None:
        return f"{cfg.overlap} {unit}"
    return f"{cfg.overlap} {unit} ({cfg.overlap_frac * 100:g}%)"


