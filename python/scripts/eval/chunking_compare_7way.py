@dataclass(frozen=True)
class ChunkConfig:
    """One named chunking configuration.

    ``kind`` selects the implementation:
      - ``"fixed_char"`` → RecursiveCharacterChunker (char sizing); ``max_tokens``
        is only the hard cap, not the primary size.
      - ``"token_window"`` → the local sliding TOKEN-window helper (primary token
        size = ``size``, overlap = ``overlap`` tokens).
      - ``"sentence"`` / ``"words"`` → Sentence/Word chunker on the token-budget
        path (``max_tokens=size``).
      - ``"semantic"`` → SemanticChunker (adaptive) with a token cap = ``size``.

    ``overlap`` is the **resolved absolute** overlap in the unit the kind sizes in
    (chars for ``fixed_char``, tokens everywhere else). ``overlap_frac`` records
    the *fraction of ``size``* it was resolved from, or ``None`` for a config that
    was written as a bare absolute. The pair is what makes a size sweep readable:
    see :func:`resolve_overlap_tokens` for why the fraction is the primary
    parameter and the absolute is derived.

    ``char_overlap`` is the char rendering of ``overlap`` that the sentence/words
    token-budget packer actually consumes (that packer's overlap argument is in
    **chars** — see ``_pack_spans_tokens``). ``overlap`` still carries the token
    intent for those kinds so the reported grid is uniform.
    """

    key: str
    kind: str
    size: int  # chars (fixed_char), tokens (token_window/sentence/words), tok-cap (semantic)
    overlap: int = 0  # chars (fixed_char) or tokens (token_window)
    char_overlap: int = 0  # explicit char overlap for sentence/words token-budget packing
    label: str = ""
    extra: dict = field(default_factory=dict)
    overlap_frac: float | None = None  # fraction of ``size`` ``overlap`` came from


# --------------------------------------------------------------------------- #
# Stage 1 of the chunking evaluation: a 24-config grid
# (docs/plans/chunking-evaluation.md § "Overlap belongs in the grid")
# --------------------------------------------------------------------------- #
#: The size ladder. All four fit the SFR 4096-token window with room, so this is a
#: retrieval-quality and storage sweep, not a context-window one.
STAGE1_SIZES: tuple[int, ...] = (256, 512, 1024, 2048)

#: Overlap as a FRACTION of size, never as an absolute token count. This is the
#: whole point of the stage. ``chunk_overlap`` is absolute today, so a size sweep
#: at a fixed ``overlap=64`` is 25.0% at size 256 but 3.1% at size 2048 — the
#: size effect and a *fading overlap effect* move together and cannot be told
#: apart. Separating them is what stage 1 exists to do. 0% is included at every
#: size because it is the cheapest configuration: the burden of proof sits on
#: overlap, which costs ``1/(1-f)`` vectors for its whole lifetime.
STAGE1_OVERLAP_FRACS: tuple[float, ...] = (0.0, 0.125, 0.25)

#: The non-``token_window`` kinds, swept over the same size ladder.
#:
#: The plan (§ "Staged", stage 1) says "12 fixed×sizes×overlaps, then 12 other
#: kinds×sizes" and does NOT say which overlap the second twelve run at. 12.5% is
#: this module's choice, made explicit here and spelled out in every label: it is
#: the shipping default's fraction (512/64), so the other-kind row is directly
#: comparable to ``fixed_tok512``.
STAGE1_OTHER_KINDS: tuple[str, ...] = ("sentence", "words", "semantic")
STAGE1_OTHER_FRAC = 0.125

#: Chars per token used to render a token overlap for the sentence/words packer,
#: whose overlap argument is in chars. 2.5 is not a measurement — production
#: measures 3.50 — it is the constant the shipping ``sentence_tok512`` /
#: ``words_tok512`` configs were written with (512 tokens × 12.5% = 64 tokens →
#: the committed ``char_overlap=160``). Keeping it reproduces those two configs
#: exactly, so the grid stays comparable with everything already measured. Change
#: it and ``test_sentence_char_overlap_matches_the_shipping_config`` goes red,
#: which is the point: it would silently re-cut every sentence/words config.
OVERLAP_CHARS_PER_TOKEN = 2.5

#: Semantic's truncation policy, declared rather than left implicit (plan § 3 —
#: "a config whose oversize handling is not pinned measures configuration, not
#: method"). Identical to the shipping ``semantic_tokcap`` policy.
SEMANTIC_POLICY = {
    "buffer_size": 3,
    "breakpoint_percentile_threshold": 80.0,
    "min_chunk_length": 500,
}

#: Grid cells that keep a pre-existing key instead of the generated one. The
#: shipping control ``fixed_tok512`` is 512 tokens / 64 overlap, and 64/512 is
#: exactly 12.5%, so it *is* a cell of this grid rather than a neighbour of one.
#: It keeps its key because the key becomes a Qdrant collection and an ES index
#: name: renaming it would make the one config that has to stay comparable across
#: stages incomparable with every result already recorded under that name, and
#: would make ``scifact_chunk_eval``'s force-included statistics reference a
#: 25th, duplicate build.
STAGE1_LEGACY_KEYS: dict[tuple[str, int, float], str] = {
    ("token_window", 512, 0.125): "fixed_tok512",
}

#: Key stem per kind, so ``token_window`` keeps the established ``fixed_tok``
#: spelling that every committed result and report already uses.
_KIND_KEY_STEM = {
    "token_window": "fixed_tok",
    "sentence": "sentence_tok",
    "words": "words_tok",
    "semantic": "semantic_tok",
}


def resolve_overlap_tokens(size: int, frac: float) -> int:
    """The absolute overlap for ``size`` at overlap fraction ``frac``.

    Rounded half-up rather than with :func:`round`'s banker's rounding, so the
    mapping is the obvious one at a ``.5`` boundary. No cell of the shipping grid
    lands on such a boundary (every ``STAGE1_SIZES`` × ``STAGE1_OVERLAP_FRACS``
    product is exact in binary floating point), so the two agree today; the
    explicit rule is for whoever adds a size or a fraction.
    """
    if not 0.0 <= frac < 1.0:
        raise ValueError(
            f"overlap fraction must be in [0, 1) — got {frac!r}. At f >= 1 a "
            f"window never advances; inflation is 1/(1-f) and diverges."
        )
    return int(math.floor(size * frac + 0.5))


def overlap_frac_key(frac: float) -> str:
    """Key fragment naming an overlap fraction, e.g. ``0.125`` → ``ov12_5pct``.

    Percent with ``_`` for the decimal point: unambiguous to a reader (12.5
    percent, not 125 tokens), and legal in both a Qdrant collection name and an
    Elasticsearch index name, which is what these keys become.
    """
    pct = frac * 100.0
    text = f"{pct:.1f}".rstrip("0").rstrip(".")
    return "ov" + text.replace(".", "_") + "pct"


def stage1_configs() -> list[ChunkConfig]:
    """The 24 stage-1 configs: 12 ``token_window`` cells + 12 other-kind cells.

    12 = ``STAGE1_SIZES`` (4) × ``STAGE1_OVERLAP_FRACS`` (3), all
    ``token_window``; then 12 = ``STAGE1_OTHER_KINDS`` (3) × ``STAGE1_SIZES`` (4)
    at ``STAGE1_OTHER_FRAC``. Every overlap is resolved from a fraction, and both
    the fraction and the resolved absolute appear in the label.
    """
    out: list[ChunkConfig] = []
    for size in STAGE1_SIZES:
        for frac in STAGE1_OVERLAP_FRACS:
            out.append(_stage1_cell("token_window", size, frac))
    for kind in STAGE1_OTHER_KINDS:
        for size in STAGE1_SIZES:
            out.append(_stage1_cell(kind, size, STAGE1_OTHER_FRAC))
    return out


def _stage1_cell(kind: str, size: int, frac: float) -> ChunkConfig:
    """One grid cell, with its overlap resolved from ``frac`` for this ``size``."""
    overlap = resolve_overlap_tokens(size, frac)
    pct = f"{frac * 100:g}%"
    key = STAGE1_LEGACY_KEYS.get(
        (kind, size, frac), f"{_KIND_KEY_STEM[kind]}{size}_{overlap_frac_key(frac)}"
    )
    if kind == "token_window":
        return ChunkConfig(
            key=key, kind=kind, size=size, overlap=overlap, overlap_frac=frac,
            label=f"fixed TOKEN window {size}/{overlap} ({pct} of size)",
        )
    if kind in ("sentence", "words"):
        char_overlap = int(math.floor(overlap * OVERLAP_CHARS_PER_TOKEN + 0.5))
        name = "sentence (Punkt)" if kind == "sentence" else "words"
        return ChunkConfig(
            key=key, kind=kind, size=size, overlap=overlap,
            char_overlap=char_overlap, overlap_frac=frac,
            label=f"{name}, pack to <={size} tokens, {pct} overlap "
                  f"= {overlap} tok ~ {char_overlap} chars",
        )
    if kind == "semantic":
        # The semantic chunker is adaptive: it has no overlap of its own, and
        # ``size`` is its token CAP. chunk_size/chunk_overlap reach only its
        # oversized-doc fixed-token fallback window — which is exactly where the
        # grid's budget should apply, so thread them rather than leaving that
        # fallback on make_chunker's 512/64 defaults. Passing them through
        # ``extra`` keeps the shipping ``semantic_tokcap`` / ``semantic_pooled``
        # configs (whose ``extra`` carries no such keys) bit-identical.
        return ChunkConfig(
            key=key, kind=kind, size=size, overlap=overlap, overlap_frac=frac,
            label=f"semantic (buffer 3 / pct 80 / min 500), token-cap {size}; "
                  f"adaptive — {pct} = {overlap} tok applies only to the "
                  f"oversized-doc fallback window",
            extra={**SEMANTIC_POLICY, "chunk_size": size, "chunk_overlap": overlap},
        )
    raise ValueError(f"no stage-1 recipe for kind {kind!r}")


