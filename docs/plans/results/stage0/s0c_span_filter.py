"""The #513 locator fix, as a **post-filter** on label records — and its verification.

**The defect (#513).** In `s0_label_r31.py` the located quote is snapped outward by
`s0_label_r3._snap`, which emits *one span per unit the interval touches*. When a quote's
first and last sentence locate in **different** units, every unit strictly between them is
emitted **whole**. On the 5 MB compendium document (`2016_1` / PMC4212306, 1,694 units) one
model span became 986 emitted spans covering 22,366 sentences. It fired once in 9,240
readings and moved a pre-registered headline mean by 128 %.

**The fix, as #513 states it.** When the two anchors land in different units, do not fill
the intervening units: emit only the located **first-anchor sentence run** and the located
**last-anchor sentence run** as a two-span set, and flag the record.

**Why a post-filter and not a locator change.** The r3.1 labels already exist (#507, #512)
and the confirmation labels are generated by the same, byte-identical prompt and locator —
changing `_snap` would change the instrument between the two sets, and r3 §3.7's whole
argument is that the dev calibration and the confirmation labels come from *one*
instrument. A post-filter applied identically to both keeps that true, and is verifiable:
§ "verify" below re-reads the dev instrument through the filter and shows the reliability
#512 measured is unmoved.

**Recovering the fill groups from a stored record.** A record stores emitted spans, not the
locator's intermediate interval. A `_snap` cross-unit output has an exact signature, and
that signature is what is matched here — never a threshold on size:

* the spans are **consecutive in the set's span list** (``_snap`` appends them in unit
  order);
* their units are **adjacent in the document's unit order** (the order `_snap` walks);
* every span strictly between the first and the last covers its unit **whole**
  (``first_sentence == 0`` and ``last_sentence == n_sentences - 1``);
* the first span runs to the **end** of its unit and the last starts at its unit's
  **first** sentence — which is what an interval crossing those boundaries produces.

and, as a precondition, the record's own bookkeeping must say a cross-unit split happened
(``vstats["split_across_units"] > 0``). A record with no such event is passed through
untouched, so the filter can never rewrite a genuinely multi-span evidence set that the
model itself emitted as separate spans.

A group of exactly two spans is already "the two anchored runs": it is flagged and left
alone. A group of three or more loses its interior fills.

Also recorded per record (#513's second ask): the **blow-up flag**
``spans_emitted >= 10 × max(spans_seen, 1)``, read off ``vstats``.

Usage::

    python3 s0c_span_filter.py --selftest         # offline, synthetic records
    python3 s0c_span_filter.py --verify-dev       # filter artifacts/r31ext/, recompute 0.92
    python3 s0c_span_filter.py --in A.jsonl --out B.jsonl

Reads and writes only: ``$STAGE0_BIG/work/r31ext-filtered/`` (NEW — the r31ext label files
are never modified), ``$STAGE0_BIG/work/conf/labels/``, and ``artifacts/conf-a/``.
No endpoint is contacted and no store client is constructed.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import sys
import time

import s0c_common as Q          # noqa: I001
import s0_common as C
from s0_label import segment

BLOWUP_RATIO = 10               # #513 / s0_labelgates_r31ext.OUTLIER_EMITTED_RATIO

_DOCS: dict[str, str] = {}
_UNITS: dict[str, list] = {}
_SHAPE: dict[str, tuple[dict, dict]] = {}


def _load_corpus() -> None:
    if _DOCS:
        return
    for line in open(C.WORK / "docs.jsonl"):
        r = json.loads(line)
        _DOCS[r["docno"]] = r["text"]
    for line in open(C.WORK / "units.jsonl"):
        r = json.loads(line)
        _UNITS[r["docno"]] = r["units"]


def unit_shape(docno: str) -> tuple[dict, dict]:
    """``({unit_index: n_sentences}, {unit_index: position in unit order})``.

    Derived from the same segmentation the labeler used, so a unit that carries no
    sentence is absent from both — which is exactly how ``_snap`` walks them.
    """
    if docno not in _SHAPE:
        _load_corpus()
        seg = segment(_DOCS[docno], _UNITS[docno])
        nsent, pos = {}, {}
        for ui, _title, sents in seg:
            if not sents:
                continue
            pos[ui] = len(pos)
            nsent[ui] = len(sents)
        _SHAPE[docno] = (nsent, pos)
    return _SHAPE[docno]


def _continues(a: dict, b: dict, nsent: dict, pos: dict) -> bool:
    """Is ``b`` the next unit of a ``_snap`` interval that started at ``a``?"""
    pa, pb = pos.get(a["unit"]), pos.get(b["unit"])
    if pa is None or pb is None or pb != pa + 1:
        return False
    return (a["last_sentence"] == nsent[a["unit"]] - 1
            and b["first_sentence"] == 0)


def _is_whole_unit(sp: dict, nsent: dict) -> bool:
    return sp["first_sentence"] == 0 and sp["last_sentence"] == nsent[sp["unit"]] - 1


def filter_spans(spans: list[dict], nsent: dict, pos: dict) -> tuple[list[dict], int, int]:
    """Return (kept spans, groups collapsed, spans dropped)."""
    out: list[dict] = []
    groups = dropped = 0
    i = 0
    n = len(spans)
    while i < n:
        j = i
        while j + 1 < n and _continues(spans[j], spans[j + 1], nsent, pos):
            j += 1
        if j > i:
            groups += 1
            interior = spans[i + 1:j]
            if all(_is_whole_unit(sp, nsent) for sp in interior):
                out.append(spans[i])
                out.append(spans[j])
                dropped += len(interior)
            else:                       # not a fill: keep everything, still counted
                out.extend(spans[i:j + 1])
        else:
            out.append(spans[i])
        i = j + 1
    return out, groups, dropped


def n_sentences(spans: list[dict]) -> int:
    return len({(sp["unit"], k) for sp in spans
                for k in range(sp["first_sentence"], sp["last_sentence"] + 1)})


def filter_record(rec: dict) -> dict:
    """Apply the #513 post-filter to one label record. Returns a NEW record."""
    v = rec.get("vstats") or {}
    emitted, seen = v.get("spans_emitted", 0), v.get("spans_seen", 0)
    blowup = emitted >= BLOWUP_RATIO * max(seen, 1)
    flag = {"applied": False, "cross_unit_events_recorded": v.get("split_across_units", 0),
            "groups_collapsed": 0, "spans_dropped": 0, "sentences_dropped": 0,
            "blowup": bool(blowup), "spans_emitted": emitted, "spans_seen": seen}
    if not v.get("split_across_units"):
        return {**rec, "span_filter": flag}

    nsent, pos = unit_shape(rec["docno"])
    before = sum(n_sentences(s["spans"]) for s in rec["sets"])
    new_sets, groups, dropped = [], 0, 0
    for s in rec["sets"]:
        kept, g, d = filter_spans(s["spans"], nsent, pos)
        groups += g
        dropped += d
        new_sets.append({**s, "spans": kept})
    after = sum(n_sentences(s["spans"]) for s in new_sets)
    flag.update({"applied": bool(dropped or groups), "groups_collapsed": groups,
                 "spans_dropped": dropped, "sentences_dropped": before - after})
    out = {**rec, "sets": new_sets, "span_filter": flag,
           "n_spans": sum(len(s["spans"]) for s in new_sets)}
    if dropped:
        out["n_spans_prefilter"] = rec.get("n_spans")
    return out


def filter_file(src: pathlib.Path, dst: pathlib.Path) -> dict:
    t0 = time.time()
    n = touched = groups = dropped = sent = blow = 0
    tmp = dst.with_suffix(dst.suffix + ".tmp")
    flagged = []
    with open(tmp, "w") as f:
        for line in open(src):
            if not line.strip():
                continue
            rec = json.loads(line)
            out = filter_record(rec)
            fl = out["span_filter"]
            n += 1
            groups += fl["groups_collapsed"]
            dropped += fl["spans_dropped"]
            sent += fl["sentences_dropped"]
            blow += int(fl["blowup"])
            if fl["applied"]:
                touched += 1
                flagged.append({"topic": rec["topic"], "docno": rec["docno"],
                                "presentation": rec.get("presentation"),
                                "judge": rec.get("judge"), **fl})
            f.write(json.dumps(out) + "\n")
    tmp.replace(dst)
    return {"src": str(src), "dst": str(dst), "records": n,
            "records_filtered": touched, "groups_collapsed": groups,
            "spans_dropped": dropped, "sentences_dropped": sent,
            "records_flagged_blowup": blow,
            "flagged": flagged[:50],
            "sha256_out": Q.sha256_file(dst),
            "seconds": round(time.time() - t0, 1)}


# ---------------------------------------------------------------- dev verification
def verify_dev(outdir: pathlib.Path) -> dict:
    """Filter the committed r3.1-extension dev labels and re-read #512's reliability.

    The estimator is `s0_labelgates_r31ext.support_reliability` — **imported, not
    re-implemented** — read on the same pooled interleaved order (s0,q0,s1,q1,… then
    scout 10..19) at n = 30, with the same seed and the same 20 half-splits. The
    requirement: the filtered instrument reproduces the committed reliability to ±0.01.
    """
    import s0_labelgates_r31ext as X
    import s0_labelgates_r31 as G

    src_dir = C.WORK / "r31ext"
    dst_dir = C.WORK / "r31ext-filtered"          # NEW — r31ext is never written to
    dst_dir.mkdir(parents=True, exist_ok=True)
    files = {}
    for judge in ("scout", "qwen"):
        files[judge] = filter_file(src_dir / f"labels-r31-{judge}.jsonl",
                                   dst_dir / f"labels-r31-{judge}.jsonl")

    committed = json.loads((Q.HERE / "artifacts" / "r31ext" /
                            "gates-r31ext.json").read_text())
    ref = next(x for x in committed["pooled"]["support_reliability"]
               if x["n_readings"] == 30)
    ref_excl = next(x for x in committed["pooled"]["support_reliability_excluding_blowups"]
                    if x["n_readings"] == 30)

    def pooled_from(directory: pathlib.Path):
        X.EXT = directory
        loaded = {j: X.load_ext(j) for j in X.JUDGES}
        keys = sorted(set(G.complete(loaded["scout"], X.N_SCOUT))
                      & set(G.complete(loaded["qwen"], X.N_QWEN)))
        Rs = {k: X.readings_for(loaded["scout"], k, range(X.N_SCOUT)) for k in keys}
        Rq = {k: X.readings_for(loaded["qwen"], k, range(X.N_QWEN)) for k in keys}
        pooled = {}
        for k in keys:
            inter = [x for pair in zip(Rs[k][:X.N_QWEN], Rq[k]) for x in pair]
            pooled[k] = inter + Rs[k][X.N_QWEN:]
        return pooled, len(keys)

    before, n_pairs_b = pooled_from(src_dir)
    after, n_pairs_a = pooled_from(dst_dir)
    assert n_pairs_b == n_pairs_a, (n_pairs_b, n_pairs_a)
    rel_before = X.support_reliability(before, 30)
    rel_after = X.support_reliability(after, 30)

    sb_b = rel_before["spearman_brown_full_n"]
    sb_a = rel_after["spearman_brown_full_n"]
    delta = round(sb_a - sb_b, 4)
    ok_repro = abs(sb_b - ref["spearman_brown_full_n"]) < 1e-9
    out = {
        "what": "the #513 post-filter applied to the committed r3.1-extension DEV labels, "
                "and #512's reliability estimator re-read through it",
        "estimator": "s0_labelgates_r31ext.support_reliability (imported), n = 30 pooled "
                     f"readings, seed {X.SEED_ANALYSIS} + 30, {X.N_DRAWS} half-splits",
        "pairs": n_pairs_a,
        "files": files,
        "committed_gates_r31ext": {
            "split_half_r_at_30": ref["split_half_r"],
            "spearman_brown_at_30": ref["spearman_brown_full_n"],
            "spearman_brown_at_30_excluding_blowups": ref_excl["spearman_brown_full_n"]},
        "recomputed_unfiltered": {"split_half_r": rel_before["split_half_r"],
                                  "spearman_brown": sb_b},
        "recomputed_filtered": {"split_half_r": rel_after["split_half_r"],
                                "spearman_brown": sb_a},
        "delta_spearman_brown": delta,
        "requirement": "|delta| <= 0.01 — the instrument must be the same on the dev set "
                       "and on the confirmation set",
        "VERDICT": "PASS" if abs(delta) <= 0.01 else "FAIL",
        "reproduces_committed_number": ok_repro,
        "provenance": Q.provenance(),
    }
    outdir.mkdir(parents=True, exist_ok=True)
    Q.atomic_json(outdir / "span-filter-dev-verification.json", out)
    return out


# ---------------------------------------------------------------- selftest
def selftest() -> dict:
    """Offline. Synthetic unit shapes; contacts nothing and reads no corpus."""
    out: dict = {}
    nsent = {0: 4, 1: 3, 2: 5, 3: 2}
    pos = {0: 0, 1: 1, 2: 2, 3: 3}

    def sp(u, a, b):
        return {"unit": u, "unit_title": f"U{u}", "first_sentence": a,
                "last_sentence": b, "start": 0, "end": 1}

    # a genuine cross-unit fill: 0 (from s2 to end) | 1 whole | 2 whole | 3 (s0..s0)
    fill = [sp(0, 2, 3), sp(1, 0, 2), sp(2, 0, 4), sp(3, 0, 0)]
    kept, g, d = filter_spans(fill, nsent, pos)
    assert g == 1 and d == 2 and kept == [fill[0], fill[-1]], (kept, g, d)
    assert n_sentences(fill) == 2 + 3 + 5 + 1 and n_sentences(kept) == 3
    out["fill_collapsed"] = "ok (4 spans -> 2, 11 sentences -> 3)"

    # a two-span cross-unit output is ALREADY the two anchored runs: unchanged, flagged
    two = [sp(0, 2, 3), sp(1, 0, 1)]
    kept, g, d = filter_spans(two, nsent, pos)
    assert kept == two and g == 1 and d == 0
    out["two_span_group_untouched"] = "ok"

    # a genuine multi-span evidence set in NON-adjacent units is never touched
    real = [sp(0, 1, 1), sp(2, 3, 3)]
    kept, g, d = filter_spans(real, nsent, pos)
    assert kept == real and g == 0 and d == 0
    out["multi_span_set_untouched"] = "ok"

    # adjacent units but NOT boundary-to-boundary: not a fill signature
    adj = [sp(0, 1, 2), sp(1, 1, 2)]
    kept, g, d = filter_spans(adj, nsent, pos)
    assert kept == adj and g == 0 and d == 0
    out["adjacent_but_not_boundary_untouched"] = "ok"

    # interior span that is NOT a whole unit: the group is kept whole, and counted
    notfill = [sp(0, 2, 3), sp(1, 0, 1), sp(2, 0, 4)]
    kept, g, d = filter_spans(notfill, nsent, pos)
    assert kept == notfill and g == 1 and d == 0
    out["non_fill_interior_kept"] = "ok"

    # the record gate: no recorded cross-unit event -> passthrough, no rewrite
    rec = {"topic": "2014_1", "docno": "X", "sets": [{"spans": fill}],
           "vstats": {"split_across_units": 0, "spans_seen": 1, "spans_emitted": 4},
           "n_spans": 4}
    got = filter_record(rec)
    assert got["sets"][0]["spans"] == fill and got["span_filter"]["applied"] is False
    out["passthrough_without_recorded_event"] = "ok"

    # the blow-up flag is read off vstats, by mechanism, not by size. Checked on the
    # passthrough path so the selftest needs no corpus.
    f2 = filter_record({**rec, "vstats": {"split_across_units": 0, "spans_seen": 22,
                                          "spans_emitted": 986}})["span_filter"]
    f3 = filter_record({**rec, "vstats": {"split_across_units": 0, "spans_seen": 22,
                                          "spans_emitted": 219}})["span_filter"]
    assert f2["blowup"] is True and f3["blowup"] is False
    out["blowup_flag"] = "ok (986 >= 10 x 22 flagged; 219 < 220 not flagged)"
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--selftest", action="store_true")
    ap.add_argument("--verify-dev", action="store_true")
    ap.add_argument("--in", dest="src")
    ap.add_argument("--out", dest="dst")
    ap.add_argument("--outdir", default=str(Q.ART))
    args = ap.parse_args()
    if args.selftest:
        print(json.dumps(selftest(), indent=1))
        return
    if args.verify_dev:
        out = verify_dev(pathlib.Path(args.outdir))
        print(json.dumps({k: out[k] for k in
                          ("pairs", "committed_gates_r31ext", "recomputed_unfiltered",
                           "recomputed_filtered", "delta_spearman_brown", "VERDICT",
                           "reproduces_committed_number")}, indent=1))
        print(json.dumps({j: {k: v for k, v in f.items() if k != "flagged"}
                          for j, f in out["files"].items()}, indent=1))
        return
    if not (args.src and args.dst):
        raise SystemExit("--in and --out are required (or --selftest / --verify-dev)")
    st = filter_file(pathlib.Path(args.src), pathlib.Path(args.dst))
    print(json.dumps({k: v for k, v in st.items() if k != "flagged"}, indent=1))


if __name__ == "__main__":
    sys.exit(main())
