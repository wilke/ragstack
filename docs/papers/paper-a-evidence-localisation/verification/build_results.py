def dp_of(x) -> int | None:
    if isinstance(x, bool) or not isinstance(x, float):
        return 0 if isinstance(x, int) and not isinstance(x, bool) else None
    s = repr(x)
    return len(s.split(".")[1]) if "." in s and "e" not in s else 6


FIT_KEYS = ("Vmax", "Km", "r2", "projected_U20", "frac_of_asymptote", "marginal_gain",
            "mean_distinct", "observed_over")


def cmp_scalar(c, b, key=""):
    """'eq' | 'round' | 'diff' | 'skip' for committed c vs recomputed b.

    Integers compare exactly. A float may differ by one unit in its last printed digit
    ('round'); a curve-fit quantity (FIT_KEYS) by up to five, because the harness fits the
    mean curve after rounding it to 4 decimals and reports parameters from a finite grid,
    while this recomputation fits the unrounded curve by golden-section search."""
    if b is None and c is None:
        return "eq"
    if b is None:
        return "skip"
    if isinstance(c, (str, bool)) or c is None or b is None:
        return "eq" if c == b else "diff"
    if isinstance(c, (int, float)) and isinstance(b, (int, float)):
        if isinstance(c, int) and float(b).is_integer():
            return "eq" if int(b) == c else "diff"
        dp = dp_of(c) if isinstance(c, float) else 0
        if round(float(b), dp) == round(float(c), dp) or math.isclose(b, c, rel_tol=1e-9):
            return "eq"
        ulps = 5 if any(k in key for k in FIT_KEYS) else 1
        if dp > 0 and abs(b - c) <= ulps * 1.0001 * 10 ** (-dp):
            return "round"
        return "diff"
    return "eq" if c == b else "diff"


def compare(c, b):
    if isinstance(c, dict):
        if not isinstance(b, dict):
            return "diff", {}
        parts = {k: cmp_scalar(v, b.get(k, "<<missing>>"), k) for k, v in c.items()}
        parts = {k: v for k, v in parts.items() if v != "skip"}
        worst = ("diff" if "diff" in parts.values() else
                 "round" if "round" in parts.values() else "eq")
        return worst, {k: v for k, v in parts.items() if v != "eq"}
    return cmp_scalar(c, b), {}



def resolve_rerun(claim, side_dir: pathlib.Path):
    rel = RERUN.get(claim["source"])
    if claim["source"].endswith("r31ext/predictions.json"):
        # the pre-registration file is not regenerated by the gate script; --prefit is
        p = side_dir / "r31ext" / "prefit.json"
        if not p.exists():
            return None, "no prefit output"
        pf = json.loads(p.read_text())
        pr = pf["P_ext_2_projection"]
        rel10 = pf["reliability_at_10"]
        m = {"P_ext_2": {"Vmax_prereg": pr["Vmax"], "Km_prereg": pr["Km"], "r2_prereg": pr["r2"],
                         "projected_U20": pr["projected_U20"],
                         "projected_U20_as_fraction_of_Vmax": pr["projected_U20_as_fraction_of_Vmax"],
                         "threshold_U20": pr["within_10pct_of_asymptote_requires_U20_at_least"]},
             "_reliability_at_10": rel10}
        if claim["id"] == "prereg-p-ext-2-fit-parameters":
            v = dict(m["P_ext_2"])
            v["secondary_threshold_relative_error"] = None
            return {k: v.get(k) for k in claim["value"]}, (
                "--prefit output; secondary_threshold_relative_error is a registered "
                "constant the prefit does not compute")
        return None, "pre-registered constant: not produced by any script"
    if rel is None:
        return None, "source is not a gate-script output"
    p = side_dir / rel
    if not p.exists():
        return None, f"{p} missing"
    doc = json.loads(p.read_text())
    node = resolve(doc, claim["pointer"])
    v = claim["value"]
    if isinstance(v, dict):
        return {k: resolve(node, k) for k in v}, None
    return node, None


