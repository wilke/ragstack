def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--a", required=True, help="OUT of reproduce_pinned.sh")
    ap.add_argument("--b", required=True, help="directory holding recompute_*.json")
    ap.add_argument("--out", required=True,
                    help="where to write RESULTS-recompute.json. Required, so a re-run cannot "
                         "overwrite the committed file by accident; pass a scratch path and "
                         "diff it against the committed one")
    args = ap.parse_args()
    a_dir = pathlib.Path(args.a)
    bdir = pathlib.Path(args.b)
    B = {p.stem: json.loads(p.read_text())["results"] for p in bdir.glob("recompute_*.json")}
    coord = json.loads((bdir / "coord_check.json").read_text())
    reloc = json.loads((bdir / "relocate_main.json").read_text()) if (
        bdir / "relocate_main.json").exists() else None
    bv = b_values(B)
    claims = json.loads(V.CLAIMS.read_text())["claims"]
    rows, counts = {}, {}
    for c in claims:
        cid = c["id"]
        A, a_note = resolve_rerun(c, a_dir / "pin")
        M, _ = resolve_rerun(c, a_dir / "main")
        row = {"committed": c["value"], "source": c["source"], "pointer": c["pointer"],
               "reproduced_A": A, "main_recomputed": M, "recomputed_B": bv.get(cid)}
        if a_note:
            row["reproduced_A_note"] = a_note
        if cid in QUARANTINE:
            row["status"] = "NOT RECOMPUTED (quarantine)"
            row["why"] = ("confirmation-run data is quarantined; resolved against the committed "
                          "artifact and checked for internal arithmetic only (recompute_derived)")
        elif cid in CONSTANTS:
            row["status"] = f"NOT RECOMPUTED ({CONSTANTS[cid]})"
        else:
            st_b, parts = compare(c["value"], bv.get(cid))
            st_a = compare(c["value"], A)[0] if A is not None else None
            row["A_vs_committed"] = st_a
            row["B_parts_not_equal"] = parts
            if st_b == "eq":
                row["status"] = "MATCH"
            elif st_b == "round" and not cid.startswith(("graded-support", "judge-scout",
                                                         "judge-qwen")):
                row["status"] = "MATCH-ROUNDING"
                row["why"] = ROUND_WHY
            else:
                row["status"] = "MISMATCH"
            if cid in AMBIG:
                row["status"] = "AMBIGUOUS DEFINITION"
                row["why"] = AMBIG[cid]
            if cid in FINDING:
                row["finding"] = FINDING[cid]
        if row["status"] == "MISMATCH" and cid.startswith(("graded-support", "judge-")):
            row["why"] = MISMATCH_WHY
        rows[cid] = row
        counts[row["status"]] = counts.get(row["status"], 0) + 1
    out = {"what": "Paper A — independent recomputation of every claim (Layers A, B, C) and "
                   "the CURRENT-CODE DELTA",
           "provenance": V.provenance(), "status_counts": counts,
           "current_code_delta": {
               "coordinate_check": {k: coord[k] for k in (
                   "EQUAL", "pin_commit", "main_commit", "n_docs", "n_unit_texts", "nltk",
                   "label_spans_vs_main_offsets")} | {
                   "fingerprint_sha256": coord["fingerprint_main_sentence_spans_fingerprint"]["sha256"],
                   "texts_sha256": coord["fingerprint_main_sentence_spans_fingerprint"]["texts_sha256"]},
               "relocate_main": None if reloc is None else reloc["results"],
               "NEEDS_RELABEL": [] if coord["EQUAL"] else ["see README"]},
           "layer_c": B["recompute_derived"],
           "claims": rows}
    pathlib.Path(args.out).write_text(json.dumps(out, indent=1, default=str) + "\n")
    print(json.dumps(counts, indent=1))


if __name__ == "__main__":
    main()
