// Package render produces every file the ctl writes for a tenant or the
// fleet: tenant.env, bin/up.sh + bin/down.sh (byte-for-byte ports of
// apptainer/new-tenant.sh's render_* functions — parity_test.go runs the
// script as the oracle), the per-tenant systemd --user units, and the two
// generated nginx includes. Everything is text/template with a strict
// quoting/refusal pass so no operator-supplied value can inject config.
package render

import (
	"bytes"
	"errors"
	"fmt"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"text/template"

	"github.com/ragstack/ragstack/internal/ctl/paths"
	"github.com/ragstack/ragstack/internal/ctl/registry"
)

// Placeholders new-tenant.sh prints in --dry-run (stable, leak-free output).
const (
	PlaceholderKeyUser    = "<GENERATED:API_KEY_USER>"
	PlaceholderKeyAdmin   = "<GENERATED:API_KEY_ADMIN>"
	PlaceholderPGPassword = "<GENERATED:PG_PASSWORD>"
)

// Store kinds for the ACL/registry/job stores.
const (
	StoreSQLite   = "sqlite"
	StorePostgres = "postgres"
)

// Secrets are the three per-tenant generated secrets. Zero value + DryRun
// renders placeholders.
type Secrets struct {
	KeyUser, KeyAdmin, PGPassword string
}

// EnvOptions parameterise TenantEnv.
type EnvOptions struct {
	DryRun    bool    // render <GENERATED:*> placeholders instead of Secrets
	Secrets   Secrets // real values (ignored when DryRun)
	StoreKind string  // sqlite (default) | postgres
	PGHost    string  // postgres only
	PGPort    string  // postgres only ("5432" when unset)
	Generator string  // the "(generated by …)" attribution; default "ragstack-ctl"
}

// ScriptGenerator is new-tenant.sh's attribution; the parity test normalises
// the generator line to compare byte-for-byte.
const ScriptGenerator = "apptainer/new-tenant.sh"

// heapPattern is the JVM -Xmx grammar subset new-tenant.sh accepts in practice.
var heapPattern = regexp.MustCompile(`^[1-9][0-9]*[kmgKMG]$`)

// A DSN host/port is interpolated into an unquoted env value and a URL.
var (
	pgHostPattern = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9.-]{0,252}$`)
	pgPortPattern = regexp.MustCompile(`^[1-9][0-9]{0,4}$`)
)

func (o EnvOptions) secrets() Secrets {
	if o.DryRun {
		return Secrets{PlaceholderKeyUser, PlaceholderKeyAdmin, PlaceholderPGPassword}
	}
	return o.Secrets
}

// envData is what the tenant.env template sees.
type envData struct {
	Name, TDir, EnvFile, Generator string
	Ports                          registry.Ports
	Postgres                       bool
	PGHost, PGPort                 string
	KeyUser, KeyAdmin, PGPassword  string
}

